@pytest.mark.django_db
class TestVote:
    def test_buttons_carry_a_signed_usage_id_when_a_row_exists(self, enabled, fake):
        fake(_final("Todo bien."))
        html = _ask(login_as("view_flightpermission"))

        assert AssistantUsage.objects.count() == 1
        assert 'data-assistant-vote="1"' in html
        assert 'data-assistant-vote="-1"' in html
        assert html.count('aria-pressed="false"') == 2
        assert "data-usage-id=" in html

    def test_no_vote_when_the_answer_is_an_error(self, enabled, monkeypatch):
        class Boom(FakeClient):
            def chat(self, messages, tools=None):
                raise AssistantUnavailable("boom")

        client = Boom([])
        monkeypatch.setattr(service, "NvidiaClient", lambda: client)
        html = _ask(login_as("view_flightpermission"))

        assert "data-assistant-vote" not in html

    def test_no_vote_when_the_daily_cap_blocks_the_question(self, enabled, fake):
        enabled.AI_ASSISTANT_DAILY_CAP = 1
        AssistantUsage.objects.create(user=None, rounds=1)
        fake(_final("no debe llegar"))
        html = _ask(login_as("view_flightpermission"))

        assert "data-assistant-vote" not in html

    def test_a_real_vote_is_stored_by_the_endpoint(self, enabled, fake):
        fake(_final("Todo bien."))
        client = login_as("view_flightpermission")
        html = _ask(client)
        token = html.split('data-usage-id="')[1].split('"')[0]

        response = client.post(reverse(VOTE), {"usage_id": token, "vote": "1"})

        assert response.status_code == 204
        assert AssistantUsage.objects.get().vote == AssistantUsage.VOTE_UP

    def test_another_persons_token_is_rejected(self, enabled, fake):
        fake(_final("Todo bien."))
        html = _ask(login_as("view_flightpermission"))
        token = html.split('data-usage-id="')[1].split('"')[0]
        other = login_as("view_flightpermission", "view_aircraft")

        response = other.post(reverse(VOTE), {"usage_id": token, "vote": "1"})

        assert response.status_code == 404
        assert AssistantUsage.objects.get().vote is None

    def test_the_script_handles_failures_with_a_neutral_message(self):
        from pathlib import Path

        js = Path("static/js/assistant-panel.js").read_text(encoding="utf-8")
        assert "voteFailed" in js and "aria-pressed" in js


